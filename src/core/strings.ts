export const STRINGS_BY_LANG: Record<Lang, LocaleStrings> = {
  id: ID_STRINGS,
  en: EN_STRINGS,
};

function live<K extends keyof LocaleStrings>(key: K): LocaleStrings[K] {
  const get = (): object => STRINGS_BY_LANG[currentLang][key] as unknown as object;
  return new Proxy(ID_STRINGS[key] as unknown as object, {
    get: (_, prop) => Reflect.get(get(), prop),
    has: (_, prop) => Reflect.has(get(), prop),
    ownKeys: () => Reflect.ownKeys(get()),
    getOwnPropertyDescriptor: (_, prop) => Reflect.getOwnPropertyDescriptor(get(), prop),
  }) as unknown as LocaleStrings[K];
}

